"""
Модуль расчёта стоимости бронирования.
Чистые функции без побочных эффектов.
"""


def calculate_total(base_price: int, age: int, is_weekend: bool, promo_code: str | None) -> int:
    """
    Рассчитывает итоговую стоимость бронирования билета.
    
    Порядок применения правил:
    1. Базовая цена (должна быть > 0)
    2. Возрастная скидка 20% (age < 18 или age >= 65)
    3. Промокод STUDENT2026 (15% дополнительно) - НЕ суммируется с возрастной скидкой
    4. Наценка за выходные +100 руб
    5. Минимальная стоимость 50 руб
    
    Args:
        base_price: Базовая цена билета (целое число > 0)
        age: Возраст покупателя
        is_weekend: Является ли день выходным
        promo_code: Промокод или None
        
    Returns:
        Итоговая стоимость в рублях
    """
    # Шаг 1: Проверка базовой цены
    if base_price <= 0:
        raise ValueError("Базовая цена должна быть строго больше 0")
    
    price = base_price
    
    # Шаг 2: Возрастная скидка 20%
    has_age_discount = age < 18 or age >= 65
    
    if has_age_discount:
        price = price * 0.8  # скидка 20%
    else:
        # Шаг 3: Промокод (только если НЕТ возрастной скидки)
        if promo_code == "STUDENT2026":
            price = price * 0.85  # дополнительная скидка 15%
    
    # Шаг 4: Наценка за выходные +100 руб
    if is_weekend:
        price = price + 100
    
    # Шаг 5: Минимальная стоимость 50 руб
    price = max(price, 50)
    
    return int(round(price))